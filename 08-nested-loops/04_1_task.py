# Задача 4
# Натуральное число из n цифр является числом Армстронга, если сумма его цифр,
# возведенных в степень n, равна самому числу. Например, 153 = 13 + 53 + 33 для
# n = 3. Напишите программу, которая находит все числа Армстронга для n = 4. В
# ответе запишите все эти числа через пробел

# Четыре вложенных цикла — по одному на каждую цифру
for a in range(1, 10):  # Первая цифра (не может быть 0)
    for b in range(10):  # Вторая цифра
        for c in range(10):  # Третья цифра
            for d in range(10):  # Четвертая цифра
                # Собираем само число из цифр
                number = a * 1000 + b * 100 + c * 10 + d

                # Считаем сумму цифр в 4-й степени
                armstrong_sum = a**4 + b**4 + c**4 + d**4

                # Проверяем условие
                if number == armstrong_sum:
                    print(number, end=" ")
