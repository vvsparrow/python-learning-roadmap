# Задача 5: Простые числа
# Напишите функцию is_prime(n), которая проверяет, является ли число простым.
# (Простое число — это натуральное число больше 1,
# которое делится без остатка только на 1 и на само себя).
# Функция должна возвращать True, если число простое, и False, если нет.
# Задание:
# Вызовите функцию для числа 104729 и выведите результат.
# План:
# 1. Если n < 2, вернуть False.
# 2. Перебрать делители от 2 до корня из n (или до n-1).
# 3. Если n делится на какой-то из них без остатка — вернуть False.
# 4. Если цикл закончился — вернуть True.


def is_prime(n):
    if n < 2:
        return False
    for i in range(2, int(n**0.5) + 1):
        if n % i == 0:
            return False
    return True


print(is_prime(104729))
