# Задача 2
# Напишите программу, которая считывает 5 чисел, добавляет их в список,
# а затем создаёт копии этого списка несколькими вариантами:
# • срезом;
# • методом copy;
# • с помощью поверхностного копирования из библиотеки copy;
# • с помощью глубоко уровневого копирования из библиотеки copy;
# • приведением списка к типу список с помощью встроенной функции.
# В ответе через пробел запишите сначала
# количество созданных копий массивов, а затем сумму чисел в изначальном массиве
# для входных данных 5, 6, 7, 8, 9.

import copy


def main() -> None:
    data: list[int] = [int(input()) for _ in range(5)]

    copies: list[list[int]] = [
        data[:],
        data.copy(),
        copy.copy(data),
        copy.deepcopy(data),
        list(data),
    ]

    print(len(copies), sum(data))


if __name__ == "__main__":
    main()
